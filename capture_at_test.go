func TestCaptureExceptionAtUsesCache(t *testing.T) {
	c, tr := newTestClient(t, Options{})
	type cachedSvc struct{ valRecvSvc }
	srv := &cachedSvc{}
	key := methodKey{typ: reflect.TypeOf(srv), method: "CreateBranch"}
	t.Cleanup(func() { methodCache.Delete(key) })

	c.CaptureExceptionAt(errors.New("boom"), srv, "CreateBranch")
	if _, ok := methodCache.Load(key); !ok {
		t.Fatal("resolution was not cached")
	}

	// Replace the entry; a cache hit must return the replacement.
	methodCache.Store(key, methodEntry{ok: true, frame: Frame{Function: "cached.Fn", AbsPath: "/x/y.go", Lineno: 7}})
	c.CaptureExceptionAt(errors.New("boom"), srv, "CreateBranch")
	frames := framesOf(t, tr)
	if last := frames[len(frames)-1]; last.Function != "cached.Fn" {
		t.Errorf("last frame = %q, want cached.Fn", last.Function)
	}
}

func TestPackageCaptureExceptionAt(t *testing.T) {
	c, tr := newTestClient(t, Options{})
	globalMu.Lock()
	prev := global
	global = c
	globalMu.Unlock()
	t.Cleanup(func() {
		globalMu.Lock()
		global = prev
		globalMu.Unlock()
	})

	if id := CaptureExceptionAt(errors.New("boom"), &valRecvSvc{}, "CreateBranch"); id == "" {
		t.Fatal("empty event id")
	}
	frames := framesOf(t, tr)
	assertOrigin(t, frames, "valRecvSvc.CreateBranch")
	for _, f := range frames[:len(frames)-1] {
		if f.InApp {
			t.Errorf("capture-site frame %q has in_app true", f.Function)
		}
		if strings.HasSuffix(f.Function, ".CaptureExceptionAt") {
			t.Errorf("SDK frame %q in stack", f.Function)
		}
	}
	if caller := frames[len(frames)-2]; !strings.HasSuffix(caller.Function, "TestPackageCaptureExceptionAt") {
		t.Errorf("capture-site frame = %q, want the calling test", caller.Function)
	}
}


func TestCaptureExceptionAtOriginFrameFields(t *testing.T) {
	c, tr := newTestClient(t, Options{})
	c.CaptureExceptionAt(errors.New("boom"), &ptrRecvSvc{}, "CreateBranch")
	last := assertOrigin(t, framesOf(t, tr), "(*ptrRecvSvc).CreateBranch")
	if last.Lineno <= 0 {
		t.Errorf("lineno = %d, want > 0", last.Lineno)
	}
	if want := modulePrefix + "/capture_at_test.go"; last.Filename != want {
		t.Errorf("filename = %q, want %q", last.Filename, want)
	}
	// The test package lives inside the SDK module, so inApp classifies it as
	// SDK code; the field must still come from inApp.
	if want := inApp(last.AbsPath, last.Function); last.InApp != want {
		t.Errorf("in_app = %v, want %v", last.InApp, want)
	}
}

func TestCaptureExceptionAtCaptureSiteFramesNotInApp(t *testing.T) {
	c, tr := newTestClient(t, Options{})
	c.CaptureExceptionAt(errors.New("boom"), &ptrRecvSvc{}, "CreateBranch")
	frames := framesOf(t, tr)
	if len(frames) < 2 {
		t.Fatalf("frames = %d, want >= 2", len(frames))
	}
	for _, f := range frames[:len(frames)-1] {
		if f.InApp {
			t.Errorf("capture-site frame %q has in_app true", f.Function)
		}
	}
	// Without resolution the stdlib test runner frame is in_app (control).
	c.CaptureException(errors.New("boom"))
	inApps := 0
	for _, f := range framesOf(t, tr) {
		if f.InApp {
			inApps++
		}
	}
	if inApps == 0 {
		t.Error("control: expected an in_app frame from CaptureException")
	}
}

func TestCaptureExceptionAtNoSDKFrames(t *testing.T) {
	c, tr := newTestClient(t, Options{})
	c.CaptureExceptionAt(errors.New("boom"), &ptrRecvSvc{}, "CreateBranch")
	frames := framesOf(t, tr)
	// Frames before the origin: the last one is this test function.
	caller := frames[len(frames)-2]
	if !strings.HasSuffix(caller.Function, "TestCaptureExceptionAtNoSDKFrames") {
		t.Errorf("capture-site frame = %q, want the calling test", caller.Function)
	}
}

func TestCaptureExceptionAtUnresolvedMatchesCaptureException(t *testing.T) {
	cases := map[string]struct {
		srv    any
		method string
	}{
		"unknown method": {&ptrRecvSvc{}, "Nope"},
		"nil srv":        {nil, "CreateBranch"},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			c, tr := newTestClient(t, Options{})
			c.CaptureException(errors.New("boom"))
			want := framesOf(t, tr)
			c.CaptureExceptionAt(errors.New("boom"), tc.srv, tc.method)
			got := framesOf(t, tr)
			if len(got) != len(want) {
				t.Fatalf("frames = %d, want %d", len(got), len(want))
			}
			for i := range got {
				// Only the line of the capture call itself differs.
				got[i].Lineno, want[i].Lineno = 0, 0
				if got[i] != want[i] {
					t.Errorf("frame %d = %+v, want %+v", i, got[i], want[i])
				}
			}
		})
	}
}


type frameJSON struct {
	Function string `json:"function"`
	Filename string `json:"filename"`
	AbsPath  string `json:"abs_path"`
	Lineno   int    `json:"lineno"`
	InApp    bool   `json:"in_app"`
}

func framesOf(t *testing.T, tr *captureTransport) []frameJSON {
	t.Helper()
	ev := decodeEvent(t, tr.last)
	exc := ev["exception"].(map[string]any)["values"].([]any)[0].(map[string]any)
	raw := exc["stacktrace"].(map[string]any)["frames"].([]any)
	out := make([]frameJSON, len(raw))
	for i, r := range raw {
		m := r.(map[string]any)
		fn, _ := m["function"].(string)
		fname, _ := m["filename"].(string)
		abs, _ := m["abs_path"].(string)
		line, _ := m["lineno"].(float64)
		in, _ := m["in_app"].(bool)
		out[i] = frameJSON{Function: fn, Filename: fname, AbsPath: abs, Lineno: int(line), InApp: in}
	}
	return out
}

func assertOrigin(t *testing.T, frames []frameJSON, fn string) frameJSON {
	t.Helper()
	last := frames[len(frames)-1]
	if !strings.HasSuffix(last.Function, fn) {
		t.Errorf("last frame function = %q, want suffix %q", last.Function, fn)
	}
	if !strings.HasSuffix(last.AbsPath, "capture_at_test.go") {
		t.Errorf("last frame abs_path = %q, want capture_at_test.go", last.AbsPath)
	}
	return last
}


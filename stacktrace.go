package tiden

import (
	"reflect"
	"runtime"
	"strings"
	"sync"
)

// newStacktrace captures the calling goroutine's stack. skip is the number of
// frames to omit on top of this function (so the first reported frame is the
// caller's caller). Frames are returned outermost-first with the capture/crash
// site last — the order the Tiden UI expects.
func newStacktrace(skip int) *Stacktrace {
	pcs := make([]uintptr, 64)
	n := runtime.Callers(skip+2, pcs)
	if n == 0 {
		return nil
	}

	it := runtime.CallersFrames(pcs[:n])
	var frames []Frame
	for {
		f, more := it.Next()
		if f.Function != "" || f.File != "" {
			frames = append(frames, Frame{
				Function: f.Function,
				Filename: shortFile(f.Function, f.File),
				AbsPath:  f.File,
				Lineno:   f.Line,
				InApp:    inApp(f.File, f.Function),
			})
		}
		if !more {
			break
		}
	}
	if len(frames) == 0 {
		return nil
	}

	for i, j := 0, len(frames)-1; i < j; i, j = i+1, j-1 {
		frames[i], frames[j] = frames[j], frames[i]
	}
	return &Stacktrace{Frames: frames}
}

// inApp marks a frame as application code (vs the standard library, the module
// cache, or this SDK).
func inApp(file, fn string) bool {
	if file == "" {
		return false
	}
	if strings.Contains(file, "/pkg/mod/") {
		return false
	}
	if strings.HasPrefix(fn, "runtime.") || strings.HasPrefix(fn, modulePrefix) {
		return false
	}
	return true
}

// shortFile derives a stable "pkgpath/file.go" name from the fully-qualified
// function name and the absolute file path, so filenames don't leak the build
// machine's directory layout (abs_path keeps the full path).
func shortFile(fn, file string) string {
	base := file
	if i := strings.LastIndexByte(base, '/'); i >= 0 {
		base = base[i+1:]
	}
	pkg := fn
	if i := strings.LastIndexByte(pkg, '/'); i >= 0 {
		dir, leaf := pkg[:i+1], pkg[i+1:]
		if d := strings.IndexByte(leaf, '.'); d >= 0 {
			leaf = leaf[:d]
		}
		pkg = dir + leaf
	} else if d := strings.IndexByte(pkg, '.'); d >= 0 {
		pkg = pkg[:d]
	}
	if pkg == "" || base == "" {
		return base
	}
	return pkg + "/" + base
}

// methodKey identifies a resolved method in methodCache.
type methodKey struct {
	typ    reflect.Type
	method string
}

// methodEntry is a cached resolution; ok is false when the method could not be
// resolved, so failures are cached too.
type methodEntry struct {
	frame Frame
	ok    bool
}

// methodCache maps methodKey to methodEntry. Resolution runs only on the error
// path and each method resolves once per process.
var methodCache sync.Map

// resolveMethodFrame returns a frame for the source location of method on srv.
// It reports false when srv is nil, the method does not exist, or the method is
// a compiler-generated wrapper.
func resolveMethodFrame(srv any, method string) (Frame, bool) {
	if srv == nil || method == "" {
		return Frame{}, false
	}
	t := reflect.TypeOf(srv)
	key := methodKey{typ: t, method: method}
	if v, ok := methodCache.Load(key); ok {
		e := v.(methodEntry)
		return e.frame, e.ok
	}
	e := lookupMethodFrame(t, method)
	methodCache.Store(key, e)
	return e.frame, e.ok
}

func lookupMethodFrame(t reflect.Type, method string) methodEntry {
	// On a pointer type, a method declared on the value receiver is an
	// <autogenerated> wrapper, so try the element type first.
	var m reflect.Method
	var found bool
	if t.Kind() == reflect.Pointer {
		m, found = t.Elem().MethodByName(method)
	}
	if !found {
		m, found = t.MethodByName(method)
	}
	if !found {
		return methodEntry{}
	}
	f := runtime.FuncForPC(m.Func.Pointer())
	if f == nil {
		return methodEntry{}
	}
	file, line := f.FileLine(f.Entry())
	if file == "" || file == "<autogenerated>" {
		return methodEntry{}
	}
	name := f.Name()
	return methodEntry{ok: true, frame: Frame{
		Function: name,
		Filename: shortFile(name, file),
		AbsPath:  file,
		Lineno:   line,
		InApp:    inApp(file, name),
	}}
}
